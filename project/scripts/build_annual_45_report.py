# -*- coding: utf-8 -*-
"""生成 45 城 2024 年报数据补录的交付物：CSV(UTF-8-SIG) + Markdown 核对表。"""
import json
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
ROOT = os.path.dirname(PROJ)
OUT = os.path.join(ROOT, 'data', 'out')
os.makedirs(OUT, exist_ok=True)

PATCH = json.load(open(os.path.join(PROJ, 'data', 'annual_45_patch.json'), encoding='utf-8'))
DB = json.load(open(os.path.join(ROOT, 'gjj_policy_database.json'), encoding='utf-8-sig'))
IDX = {c['city']: c for c in DB['annual_reports']['cities']}

ORDER = ('上海 深圳 重庆 佛山 中山 清远 海口 三亚 南通 徐州 盐城 金华 衢州 舟山 合肥 '
         '南昌 九江 襄阳 黄冈 衡阳 娄底 安阳 成都 泸州 乐山 西安 榆林 咸阳 丽江 红河 '
         '贵阳 遵义 唐山 朔州 大庆 营口 锦州 鞍山 丹东 抚顺 东营 福州 龙岩 石河子 廊坊').split()


def yoy(c, p):
    if c is None or p is None or not p:
        return '—', '—'
    d = round(c - p, 2)
    return f'{(c - p) / p * 100:+.2f}%', f'{d:+.2f} 亿元'


rows = []
for city in ORDER:
    o = IDX.get(city, {})
    s24 = o.get('stats_2024') or {}
    s25 = o.get('stats_2025') or {}
    w24 = (s24.get('withdraw_amount') or {}).get('value')
    l24 = (s24.get('loan_issued') or {}).get('value')
    w25 = (s25.get('withdraw_amount') or {}).get('value')
    l25 = (s25.get('loan_issued') or {}).get('value')
    p = PATCH.get(city, {})
    yw, dw = yoy(w25, w24)
    yl, dl = yoy(l25, l24)
    rows.append({
        '城市': city,
        '2024提取额(亿元)': w24 if w24 is not None else '—',
        '2025提取额(亿元)': w25 if w25 is not None else '—',
        '提取额同比': yw,
        '提取额增减': dw,
        '2024发放贷款(亿元)': l24 if l24 is not None else '—',
        '2025发放贷款(亿元)': l25 if l25 is not None else '—',
        '发放贷款同比': yl,
        '发放贷款增减': dl,
        '数据来源名称': p.get('name', ''),
        '来源类型': p.get('type', ''),
        '取数方式': '省级年报分市表' if p.get('kind') == 'provincial' else ('年报正文' if p.get('w') else '—'),
        '原文链接': p.get('url', ''),
        '备注': p.get('note', ''),
    })

# ---------- CSV ----------
csv_path = os.path.join(OUT, '公积金2024年报数据补录_45城_20260902.csv')
with open(csv_path, 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

# ---------- Markdown ----------
md = ['# 住房公积金 2024 年年度报告数据补录（45 城）',
      '',
      '补录字段：`annual_reports.cities[].stats_2024.withdraw_amount`（提取额）与 `loan_issued`（发放个人住房贷款）。',
      '同比口径：**(2025 值 − 2024 值) / 2024 值**，全部自行计算，不采用年报原文披露的同比。',
      '',
      '**结果：43/45 城补录成功；全局 132/134 城可算同比。海口、三亚因海南省全省统管、年报无市级拆分，且该两市 2025 年数据本身也缺失，无法补录。**',
      '',
      '## 一、数据总表',
      '',
      '| 城市 | 2024提取额 | 2025提取额 | 提取同比 | 2024发放贷款 | 2025发放贷款 | 贷款同比 | 来源类型 |',
      '|---|---:|---:|---:|---:|---:|---:|---|']
for r in rows:
    md.append('| {城市} | {2024提取额(亿元)} | {2025提取额(亿元)} | {提取额同比} | {2024发放贷款(亿元)} | {2025发放贷款(亿元)} | {发放贷款同比} | {来源类型} |'.format(**r))

md += ['', '## 二、来源清单（逐城可点击核对）', '',
       '| 城市 | 取数方式 | 来源类型 | 原文链接 | 备注 |',
       '|---|---|---|---|---|']
for r in rows:
    link = f'[链接]({r["原文链接"]})' if r['原文链接'] else '—'
    md.append(f'| {r["城市"]} | {r["取数方式"]} | {r["来源类型"] or "—"} | {link} | {r["备注"] or "—"} |')

md += ['', '## 三、质量校验说明', '',
       '### 省级分市表的列对齐交叉验证', '',
       '省级年报分市表是兜底源，但存在列错位风险。本次以「该省内已有市级年报的城市」做锚点验证列对齐：', '',
       '| 省份 | 锚点城市 | 市级年报值 | 省级表同值 | 结论 |',
       '|---|---|---|---|---|',
       '| 湖北 | 襄阳 | 53.44 / 29.77 | 53.44 / 29.77 | 一致 → 黄冈 40.55 / 22.01 可信 |',
       '| 四川 | 泸州 | 39.32 / 17.15 | 39.32 / 17.15 | 一致 → 乐山 36.85 / 15.47、成都 693.19 / 256.50 可信 |',
       '| 江苏 | 徐州、南通 | 128.76 / 76.43、181.11 / 68.04 | 同值 | 一致 → 盐城 99.82 / 51.51 可信 |',
       '| 河北 | 唐山 | 102.14 / 62.26 | 102.14 / 62.26 | 一致 → 廊坊 52.20 / 15.33 可信 |',
       '| 四川 | 成都 | 693.19 / 256.50（中国建设新闻网） | 693.19 / 256.50 | 双源一致 |',
       '',
       '> 河北表存在巧合陷阱：廊坊与邢台的贷款发放额同为 15.33 亿元，已按行名定位核对，非数值去重。',
       '',
       '### 关于同比大幅波动', '',
       '2024 年为楼市低谷、2025 年政策放松后反弹，因此发放贷款同比出现大起大落属真实情况，非解析错误。',
       '以下城市的同比值已逐条回到年报原文 grep 核对：', '',
       '| 城市 | 贷款同比 | 原文依据 |', '|---|---|---|',
       '| 合肥 | +62.98% | 「2024年，发放个人住房贷款1.86万笔111.76亿元，同比分别下降30.34%、14.73%」 |',
       '| 成都 | +60.56% | 「2024年，发放个人住房贷款5.05万笔256.50亿元，同比分别下降32.58%、27.40%」 |',
       '| 佛山 | +56.88% | 「2024年，发放个人住房贷款0.54万笔28.41亿元，同比分别减少42.55%、6.52%」 |',
       '| 廊坊 | +49.38% | 河北省级分市表廊坊行 0.33 万笔 / 15.33 亿元 |',
       '| 衢州 | −33.56% | 「2024年，发放个人住房贷款0.54万笔32.99亿元，同比分别下降22.86%、23.7%」 |',
       '| 黄冈 | −29.17% | 湖北省级分市表黄冈行 0.60 万笔 / 22.01 亿元 |',
       '| 福州 | −24.68% | 「2024年，发放个人住房贷款1.45万笔共89.70亿元，同比分别减少21.39%、18.20%」 |',
       '| 龙岩 | −24.24% | 「2024年，发放个人住房贷款4459笔19.47亿元，同比分别下降36.67%、27.91%」 |',
       '',
       '### 未能补录的城市', '',
       '| 城市 | 原因 |', '|---|---|',
       '| 海口 | 海南省全省统管，仅设 1 个法人机构，年报无分市拆分；该市 stats_2025 亦为空 |',
       '| 三亚 | 同海口 |',
       '']
md_path = os.path.join(OUT, '公积金2024年报数据补录_45城_20260902.md')
open(md_path, 'w', encoding='utf-8').write('\n'.join(md))

print('CSV →', csv_path)
print('MD  →', md_path)
